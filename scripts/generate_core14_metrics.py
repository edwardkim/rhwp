#!/usr/bin/env python3
"""Generate bounded Unicode ASCII advances from the retained Adobe AFMs."""
from pathlib import Path
import hashlib
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/font-metrics/adobe-core14"
# AdobeStandardEncoding's codes 39/96 differ from Unicode ASCII. Use names.
NAMES = ("space exclam quotedbl numbersign dollar percent ampersand quotesingle "
         "parenleft parenright asterisk plus comma hyphen period slash").split()
NAMES += [str(i) for i in range(10)]
NAMES[16:26] = "zero one two three four five six seven eight nine".split()
NAMES += "colon semicolon less equal greater question at".split()
NAMES += list("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
NAMES += "bracketleft backslash bracketright asciicircum underscore grave".split()
NAMES += list("abcdefghijklmnopqrstuvwxyz")
NAMES += "braceleft bar braceright asciitilde".split()
assert len(NAMES) == 95


def generate():
    result = ["// Generated by scripts/generate_core14_metrics.py; do not edit.",
              "// Adobe AFM values, in 1/1000 em. Inputs, copyrights and license:",
              "// data/font-metrics/adobe-core14/{*.afm,MustRead.html}.",
              "// Copyright (c) 1985, 1987, 1989, 1990, 1997 Adobe Systems Incorporated.",
              "// All Rights Reserved. Helvetica is a trademark of Linotype-Hell AG",
              "// and/or its subsidiaries.", ""]
    entries = []
    for index, (suffix, bold, italic) in enumerate([
        ("", False, False), ("-Bold", True, False),
        ("-Oblique", False, True), ("-BoldOblique", True, True),
    ]):
        file = SOURCE / f"Helvetica{suffix}.afm"
        text = file.read_text()
        widths = {}
        for line in text.splitlines():
            if not line.startswith("C "):
                continue
            fields = dict(field.strip().split(" ", 1) for field in line.split(";") if field.strip())
            widths[fields["N"]] = int(fields["WX"])
        values = [widths[name] for name in NAMES]
        result += [f"// {file.name} SHA-256: {hashlib.sha256(file.read_bytes()).hexdigest()}",
                   f"static CORE14_{index}_WIDTHS: [u16; 95] = [", "    " + ", ".join(map(str, values)) + ",", "];"]
        result += [f"static CORE14_{index}_RANGES: [LatinRange; 1] = [LatinRange {{",
                   f"    start: 0x20, end: 0x7e, widths: &CORE14_{index}_WIDTHS,", "}];"]
        for name in (["Helvetica"] if not suffix else ["Helvetica", f"Helvetica{suffix}"]):
            entries.append(f'    FontMetric {{ name: "{name}", bold: {str(bold).lower()}, italic: {str(italic).lower()}, em_size: 1000, latin_ranges: &CORE14_{index}_RANGES, hangul: None }},')
    result += [f"static CORE14_FONT_METRICS: [FontMetric; {len(entries)}] = [", *entries, "];", ""]
    return "\n".join(result)


if __name__ == "__main__":
    output = ROOT / "src/renderer/font_metrics_core14.rs"
    output.write_text(generate())
    subprocess.run(["rustfmt", str(output)], check=True)
