pub(super) fn kind(ch: char) -> u8 {
    let cp = ch as u32;
    let i = RANGES.partition_point(|(_, end, _)| *end < cp);
    if let Some(&(start, _, kind)) = RANGES.get(i) {
        if cp >= start {
            return kind;
        }
    }
    match ch.general_category() {
        GeneralCategory::NonspacingMark
        | GeneralCategory::EnclosingMark
        | GeneralCategory::Format => 4,
        _ => 0,
    }
}
