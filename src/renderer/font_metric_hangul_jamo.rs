pub(super) fn width(metric: &FontMetric, ch: char) -> Option<u16> {
    if metric.em_size != 1000 || !(0x1100..=0x11ff).contains(&(ch as u32)) {
        return None;
    }
    let widths = match (metric.name, metric.bold) {
        ("HCR Batang" | "함초롬바탕", false) => WIDTHS_0,
        ("HCR Batang" | "함초롬바탕", true) => WIDTHS_1,
        ("HCR Dotum" | "함초롬돋움", false) => WIDTHS_2,
        ("HCR Dotum" | "함초롬돋움", true) => WIDTHS_3,
        _ => return None,
    };
    let width = widths[(ch as u32 - 0x1100) as usize];
    (width != u16::MAX).then_some(width)
}
