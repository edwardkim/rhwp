pub(in crate::renderer::equation) fn measured(text: &str, fs: f64, dpi: f64) -> Option<f64> {
    let size = super::super::font_frame_metrics::base_unit_at_dpi(fs, dpi);
    // 독립 22pt ∠·GEQ·LEQ의 논리 em. 미측정 정체 문자 전진은 발행하지 않는다.
    if text == "∠" && size == 2200 {
        return Some(crate::renderer::hwpunit_to_px(2250, dpi));
    }
    let logical_size = (size.checked_add(75)? / 150) * 2;
    let row = ADVANCES
        .iter()
        .find(|row| u32::from(row[0]) == logical_size)?;
    let ch = text.chars().next()?;
    if text.chars().count() != 1 {
        return None;
    }
    let advance = match ch {
        'A'..='Z' => u32::from(row[1 + ch as usize - 'A' as usize]),
        'a'..='z' => u32::from(row[27 + ch as usize - 'a' as usize]),
        'θ' => u32::from(row[53]),
        '∠' => logical_size,
        _ => return None,
    };
    Some(crate::renderer::hwpunit_to_px((advance * 75) as i32, dpi))
}

/// UPM 1024의 각 기호와 근호가 공유하는 논리 1em 전진이다.
/// 독립 근호 70건의 추가 폭도 같은 em 격자를 소비함을 확인했다.
pub(super) fn em_advance(fs: f64, dpi: f64) -> Option<f64> {
    measured("∠", fs, dpi)
}
