pub(super) fn measured(ch: u8, fs: f64, dpi: f64) -> Option<f64> {
    let size = super::super::font_frame_metrics::base_unit_at_dpi(fs, dpi);
    let logical_size = (size.checked_add(75)? / 150) * 2;
    let row = ADVANCES
        .iter()
        .find(|row| u32::from(row[0]) == logical_size)?;
    let index = match ch {
        b'A'..=b'Z' => 1 + usize::from(ch - b'A'),
        b'a'..=b'z' => 27 + usize::from(ch - b'a'),
        _ => return None,
    };
    Some(crate::renderer::hwpunit_to_px(
        i32::from(row[index]) * 75,
        dpi,
    ))
}
