//! KoPub 여섯 프로그램의 실제 cmap에 있는 한자 전진 메타데이터.
//! 원본 프로그램은 복사하지 않는다. HWP5 §4.2.6의 한자 슬롯과
//! 독립 2024 Print166쪽을 대조한 #8153 계획에 여섯 입력 해시를 연결한다.
//! 수록4888자는 같은 cmap이며, 바탕 Bold의 여섯 전진 차이도 보존한다.

pub(super) fn advance_em(dotum: bool, bold: bool, ch: char) -> Option<f64> {
    let code = ch as u32;
    let (map, start): (&[u64], u32) = match code {
        0x4e00..=0x9fff => (&UNIFIED, 0x4e00),
        0xf900..=0xfaff => (&COMPATIBILITY, 0xf900),
        _ => return None,
    };
    let index = (code - start) as usize;
    if map[index / 64] & (1_u64 << (index % 64)) == 0 {
        return None;
    }
    let units = if !dotum && bold {
        BATANG_BOLD
            .binary_search_by_key(&code, |entry| entry.0)
            .ok()
            .map(|index| BATANG_BOLD[index].1)
            .unwrap_or(900)
    } else {
        900
    };
    Some(f64::from(units) / 1000.0)
}

