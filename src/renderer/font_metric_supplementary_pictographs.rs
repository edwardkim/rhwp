fn source(name: &str, bold: bool, italic: bool, ch: char) -> Option<&'static Source> {
    if italic || !(START..=END).contains(&(ch as u32)) {
        return None;
    }
    let primary = name
        .split(',')
        .next()?
        .trim()
        .trim_matches('\'')
        .trim_matches('"');
    SOURCES
        .iter()
        .find(|s| s.bold == bold && s.names.contains(&primary))
}
pub(super) fn primary_has_glyph(name: &str, bold: bool, italic: bool, ch: char) -> Option<bool> {
    let s = source(name, bold, italic, ch)?;
    Some(
        s.widths
            .is_some_and(|w| w[(ch as u32 - START) as usize] > 0),
    )
}
// 확인한 0폭은 미수집/없는 글리프와 다르다. 양수인 기존 폭 표는 그대로 우선한다.
fn zero_width(metric: &FontMetric, ch: char) -> Option<u16> {
    let s = SOURCES.iter().find(|s| {
        !metric.italic
            && s.bold == metric.bold
            && s.em == metric.em_size
            && s.names.contains(&metric.name)
    })?;
    s.zero_widths.binary_search(&(ch as u32)).ok().map(|_| 0)
}
pub(super) fn entry(metric: &FontMetric, ch: char) -> Option<(bool, u16)> {
    if let Some(zero) = zero_width(metric, ch) {
        return Some((true, zero));
    }
    let s = source(metric.name, metric.bold, metric.italic, ch)?;
    if metric.em_size != s.em {
        return None;
    }
    let width = s.widths.map_or(0, |w| w[(ch as u32 - START) as usize]);
    Some((width > 0, width))
}
pub(super) fn width(metric: &FontMetric, ch: char) -> Option<u16> {
    let (present, width) = entry(metric, ch)?;
    present.then_some(width)
}
