//! 에이전트 문서 조작 커널 — 선택자·연산 대수·앵커·검증·트랜잭션의 단일 척추.
//!
//! ## 왜 커널인가 — 지금의 편집 표면이 막는 것
//!
//! 오늘 에이전트가 rhwp 로 문서를 고치는 길은 `edit` 하위 명령 6개가 전부다
//! (`fill-fields`·`replace-text`·`set-cell`·`insert-image`·`redact`·`sanitize`).
//! 이 여섯은 각각 **자기만의 지목 문법**을 쓴다 — 셀은 `--table/--row/--col`,
//! 필드는 `--data 이름=값[k]`, 치환은 `--find/--occurrence`. 즉 "문서의 어디"를
//! 가리키는 공통 개념이 없다. 그래서 다음 세 가지가 구조적으로 불가능하다.
//!
//! 1. **임의 지목** — "3절 두 번째 표의 마지막 행 전부"를 표현할 문법이 없다.
//!    여섯 명령이 미리 뚫어 둔 구멍 밖은 손댈 수 없다.
//! 2. **되돌리기** — 편집은 파일을 덮어쓸 뿐 역연산을 남기지 않는다. 에이전트가
//!    한 단계 잘못 밟으면 복구 수단은 원본 사본뿐이고, 그건 도구가 아니라 운이다.
//! 3. **합성** — 여러 편집을 하나의 원자 단위로 묶을 수 없다. `run` 계획서가
//!    순차 실행을 주지만 중간 실패 시 앞선 단계는 이미 적용된 채 남는다(#3905 가
//!    실측한 경합과 같은 뿌리다).
//!
//! 여기에 하나 더 — 에이전트 축 모듈(`agent_profiles`·`policy_gate`·`anchor_log`·
//! `capsule_sign` …)은 전부 `main.rs` 의 `mod` 다. **바이너리 전용**이라 `bindings/
//! Native`·`tools/*`·wasm 어느 쪽도 링크할 수 없다. ROADMAP 이 업스트림 책임으로
//! 적은 "서비스 연계 표면 — MCP 서버와 공개 API 계약"이 정작 라이브러리에는 없다.
//! 다운스트림이 쓰려면 CLI 를 프로세스로 띄우는 수밖에 없고, 그건 계약이 아니라
//! 우회로다.
//!
//! ## 척추 — 여덟 층이 서로를 필요로 하는 이유
//!
//! ```text
//!   DSEL          문서의 "어디"를 값으로 만든다        (dsel)
//!    │  선택 결과는 NodeId 집합
//!    ▼
//!   Op            "무엇을"을 역연산 가능한 값으로      (op)
//!    │  연산은 자신이 건드릴 NodeId 를 선언한다
//!    ▼
//!   Anchor        NodeId 를 문서 변경에 견디게 고정    (anchor)
//!    │  적용 후 재결속(rebase)까지가 한 단위
//!    ▼
//!   Verify        사전·사후조건과 예상 효과            (verify)
//!    │  효과 예측이 없으면 dry-run 은 추측이다
//!    ▼
//!   Txn           저널·원자 적용·롤백                  (txn)
//!    │  역연산 스택이 곧 저널
//!    ▼
//!   Policy        연산별 능력 요구 ↔ 프로필 승인       (policy)
//!    │  연산이 자기 요구를 선언해야 게이트가 성립한다
//!    ▼
//!   Provenance    적용 이력의 계보·서명                (prov)
//!    │
//!    ▼
//!   Manifest      capabilities·MCP 도구 자동 산출      (manifest)
//! ```
//!
//! 층 사이의 화살표는 편의가 아니라 **정의 의존**이다. 선택자 없이는 연산이
//! 대상을 못 적고, 연산이 대상을 안 적으면 앵커가 무엇을 고정할지 모르고, 앵커가
//! 없으면 사후조건은 이동한 위치를 오검사하고, 효과 예측이 없으면 저널이 역연산을
//! 만들 수 없고, 역연산이 없으면 롤백이 없고, 연산이 능력을 선언하지 않으면
//! 게이트가 항상-참이 되고, 이 전부가 없으면 매니페스트는 빈 목록이다.
//!
//! 그래서 이 모듈군은 조각으로 쓸 수 없다. 한 층만 떼면 그 층은 컴파일은 되어도
//! 아무것도 하지 못한다 — 설계가 그렇게 생겼기 때문이지 일부러 얽어서가 아니다.
//!
//! ## 라이브러리에 두는 이유
//!
//! `pub mod agent` 는 `lib.rs` 에 있다. CLI(`rhwp agent …`)는 이 커널의 **한 소비자**
//! 일 뿐이고, MCP 서버·네이티브 바인딩·wasm 도 같은 자격으로 같은 타입을 쓴다.
//! 표면마다 편집 의미가 갈라지는 사고(#3905 계열)는 의미를 한 곳에 두는 것으로만
//! 막힌다.
//!
//! ## 결정론
//!
//! 커널 전 구간은 결정론이다 — 같은 문서·같은 연산이면 같은 산출, 같은 해시.
//! 시각·난수·환경 변수는 커널 안에 들어오지 않는다(필요한 경우 호출자가 값으로
//! 주입한다). 이는 `capsule_sign`·`anchor_log` 의 결정론 문화와 같은 규약이며,
//! 재실행 검증(`gate --deep`)이 성립하는 전제다.

pub mod dsel;

pub use dsel::{Selector, SelectorError};

/// 커널 계약 버전 — 선택자 문법·연산 대수·봉투 필드를 아우르는 단일 판번호.
///
/// 봉투 `schemaVersion`(명령별)·`capabilitiesSchemaVersion`(명령 표면)과 **분리**된
/// 축이다. 셋을 하나로 묶으면 커널 문법이 한 자 바뀔 때마다 명령 표면 계약까지
/// major 를 올려야 하고, 그러면 아무 관계 없는 소비자가 전부 깨진다.
///
/// 판올림 규칙: 문법·연산 **추가** = minor, 기존 문법의 의미 변경·삭제 = major.
/// major 는 분기 회고 승인 없이 금지한다(`capabilities` 정책과 동일).
pub const AGENT_KERNEL_VERSION: &str = "1.0";
