//! 최상위 CLI 명령 catalog.
//!
//! 이 목록은 #5511 Stage 1의 characterization 기준선이다. 아직 handler나 help 문구를
//! 소유하지 않는다. 표면을 한 번에 전환하지 않도록 먼저 명령 이름, 분류, 가시성,
//! feature, JSON·batch·MCP 참여 상태만 고정한다.

/// `capabilities.commands[].category`의 현재 값.
#[allow(dead_code)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Category {
    Batch,
    Diagnostic,
    Edit,
    Export,
    Internal,
    Query,
    Serve,
}

impl Category {
    #[allow(dead_code)]
    pub(crate) const fn as_str(self) -> &'static str {
        match self {
            Self::Batch => "batch",
            Self::Diagnostic => "diagnostic",
            Self::Edit => "edit",
            Self::Export => "export",
            Self::Internal => "internal",
            Self::Query => "query",
            Self::Serve => "serve",
        }
    }
}

/// 현재 명령이 help와 capabilities에 참여하는 방식.
#[allow(dead_code)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Visibility {
    /// help와 capabilities에 모두 보이는 명령.
    Public,
    /// capabilities에는 있지만 사람용 help에는 없는 내부 프로브.
    Hidden(&'static str),
    /// 실제 dispatch에는 있으나 두 자기서술 표면에 아직 등록되지 않은 명령.
    DispatchOnly(&'static str),
}

/// handler와 분리한 명령 표면 메타데이터.
#[allow(dead_code)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) struct CommandSpec {
    pub(crate) name: &'static str,
    pub(crate) category: Category,
    pub(crate) visibility: Visibility,
    pub(crate) requires_feature: Option<&'static str>,
    pub(crate) json_contract: bool,
    pub(crate) batch: bool,
    pub(crate) mcp: bool,
}

impl CommandSpec {
    pub(crate) const fn in_capabilities(self) -> bool {
        !matches!(self.visibility, Visibility::DispatchOnly(_))
    }

    #[allow(dead_code)]
    pub(crate) const fn in_help(self) -> bool {
        matches!(self.visibility, Visibility::Public)
    }
}

const fn spec(
    name: &'static str,
    category: Category,
    visibility: Visibility,
    requires_feature: Option<&'static str>,
    json_contract: bool,
    batch: bool,
    mcp: bool,
) -> CommandSpec {
    CommandSpec {
        name,
        category,
        visibility,
        requires_feature,
        json_contract,
        batch,
        mcp,
    }
}

