//! Synthetic nested-table Markdown regression.
#![cfg(not(target_arch = "wasm32"))]
use base64::Engine;
use rhwp::wasm_api::HwpDocument;

#[test]
fn nested_tables_keep_cell_text_and_order() {
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(FIXTURE.split_whitespace().collect::<String>())
        .unwrap();
    let doc = HwpDocument::from_bytes(&bytes).unwrap();
    let (markdown, _) = doc.extract_page_markdown_with_images_native(0).unwrap();
    for token in [
        "BEFORE",
        "INNER A",
        "INNER B",
        "INNER C",
        "INNER D",
        "DEEP VALUE",
        "AFTER",
        "OUTER RIGHT",
    ] {
        assert_eq!(markdown.matches(token).count(), 1, "{token}: {markdown}");
    }
    assert!(
        markdown.contains("| BEFORE [하위 표 1-1 참조] AFTER | OUTER RIGHT |"),
        "{markdown}"
    );
    assert!(
        markdown.contains("**하위 표 1-1 — 표 1의 1행 1열**"),
        "{markdown}"
    );
    assert!(
        markdown.contains("| INNER A [하위 표 1-1-1 참조] | INNER B |"),
        "{markdown}"
    );
    assert!(markdown.contains("| INNER C | INNER D |"), "{markdown}");
    assert!(
        markdown.contains("**하위 표 1-1-1 — 표 1-1의 1행 1열**"),
        "{markdown}"
    );
    assert!(markdown.contains("| DEEP VALUE |"), "{markdown}");
    assert!(!markdown.contains("<table>"), "{markdown}");
    assert!(!markdown.contains("<td>"), "{markdown}");
}
