//! #7702: 독립 Print의 장평·상대 크기·자간·따옴표 뒤 글자 위치를 보호한다.
//!
//! 기준 PDF는 pdf/issue7702/{curly_quote_latin_slot,ratio_steps,
//! relative_size_letter_spacing,size_ratio_relsize}-2020.pdf다.
//! PDF raw 문자 원점을 72pt→96dpi CSS px로 환산했으며 허용 오차는 ±2px다.
//! code2d500a의 전쪽 Native/fresh WASM 최저90%와 각 고정 쪽의 양쪽98% 이상을
//! 확인하고 같은 영역을 직접 확대 판독했다. 표준 혼합문 2쪽은 양쪽100%다.
//! 중요한 매개변수 조합이 있는1쪽도 함께 보호하며 기존 메트릭 관계 검사는 유지한다.
//! SVG 문자열의 실제 글자 원점을 검사하며 SVG 파일이나 전체 해시는 만들지 않는다.
//! 최종 glyph 모양은 Native/fresh WASM Visual Sweep으로 따로 검증한다.

use rhwp::document_core::DocumentCore;

type Glyph = (f64, String);
struct Line {
    baseline: f64,
    glyphs: Vec<Glyph>,
}
// (1부터 쪽, 공백을 뺀 줄 내용, Print 첫 글자 x, Print 기준선, Print 검사 글자 x)
// 따옴표는 첫 따옴표 뒤 글자(원본 index2), 장평·자간 사다리는 마지막 글자를 검사한다.
type Expected = (u32, &'static str, f64, f64, f64);
fn compact(text: &str) -> String {
    text.chars().filter(|c| !c.is_whitespace()).collect()
}
fn attr<'a>(tag: &'a str, name: &str) -> Option<&'a str> {
    let key = format!(" {name}=\"");
    let start = tag.find(&key)? + key.len();
    Some(&tag[start..start + tag[start..].find('"')?])
}
fn origin(tag: &str) -> Option<(f64, f64)> {
    if let (Some(x), Some(y)) = (attr(tag, "x"), attr(tag, "y")) {
        return Some((x.parse().ok()?, y.parse().ok()?));
    }
    let args = attr(tag, "transform")?.strip_prefix("translate(")?;
    let (x, y) = args[..args.find(')')?].split_once(',')?;
    Some((x.trim().parse().ok()?, y.trim().parse().ok()?))
}
fn lines(core: &DocumentCore, page: u32, quotes_only: bool) -> Vec<Line> {
    let svg = core
        .render_page_svg_native(page - 1)
        .expect("최종 SVG paint");
    let mut rest = svg.as_str();
    let mut lines: Vec<Line> = Vec::new();
    while let Some(start) = rest.find("<text ") {
        rest = &rest[start..];
        let end = rest.find('>').expect("text 태그 끝");
        let close = rest.find("</text>").expect("text 내용 끝");
        let text = rest[end + 1..close]
            .replace("&quot;", "\"")
            .replace("&apos;", "'")
            .replace("&lt;", "<")
            .replace("&gt;", ">")
            .replace("&amp;", "&");
        let text = compact(&text);
        if !text.is_empty() {
            let (x, y) = origin(&rest[..end]).expect("실제 글자 원점");
            assert_eq!(text.chars().count(), 1, "이 문서의 글자별 paint 계약");
            if let Some(line) = lines.iter_mut().find(|l| (l.baseline - y).abs() < 0.001) {
                line.glyphs.push((x, text));
            } else {
                lines.push(Line {
                    baseline: y,
                    glyphs: vec![(x, text)],
                });
            }
        }
        rest = &rest[close + 7..];
    }
    lines.sort_by(|a, b| a.baseline.total_cmp(&b.baseline));
    for line in &mut lines {
        line.glyphs.sort_by(|a, b| a.0.total_cmp(&b.0));
    }
    if quotes_only {
        lines.retain(|l| {
            l.glyphs
                .iter()
                .map(|(_, t)| t.as_str())
                .collect::<String>()
                .starts_with("가“가”가‘가’")
        });
    }
    lines
}
fn check(input: &str, pages: u32, quotes_only: bool, expected: &[Expected]) {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(input);
    let core = DocumentCore::from_bytes(&std::fs::read(path).expect("원본")).expect("문서 열기");
    assert_eq!(core.page_count(), pages, "독립 Print 전체 쪽수");
    for page in 1..=pages {
        let actual = lines(&core, page, quotes_only);
        let want: Vec<_> = expected.iter().filter(|e| e.0 == page).collect();
        assert_eq!(actual.len(), want.len(), "{page}쪽 줄의 누락·중복 없음");
        for (index, (line, &&(_, text, x, y, probe_x))) in
            actual.iter().zip(want.iter()).enumerate()
        {
            assert_eq!(
                line.glyphs
                    .iter()
                    .map(|(_, t)| t.as_str())
                    .collect::<String>(),
                text,
                "{page}쪽 줄{index} 내용·순서"
            );
            let (probe_name, probe_index) = if quotes_only {
                ("첫 따옴표 뒤 글자 x", 2)
            } else {
                ("끝 글자 x", line.glyphs.len() - 1)
            };
            for (name, got, print) in [
                ("첫 글자 x", line.glyphs[0].0, x),
                ("기준선", line.baseline, y),
                (probe_name, line.glyphs[probe_index].0, probe_x),
            ] {
                assert!(
                    (got - print).abs() <= 2.0,
                    "{page}쪽 줄{index} {name}: Print {print}, 실제 {got}"
                );
            }
        }
    }
}

