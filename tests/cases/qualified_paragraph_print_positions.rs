//! #7816・#7824: 독립 한컴 Print에서 확인한 문단 원점과 이어받기를 보호한다.
//!
//! 원본은 samples/issue7816/*.hwpx 및 issue7824/synth_ladder_spacing_before.hwpx,
//! 기준은 같은 이름의 pdf/issue7816/*-2020.pdf 및 pdf/issue7824/*-2020.pdf다.
//! 기대 좌표는 PDF 문자 원점을 72pt에서 96dpi CSS px로 환산했다. 허용 오차는 ±2px다.
//! code2d500a의 전쪽 Native/fresh WASM 최저값은 각각99% 이상이며 같은 쪽의
//! Print/Native/WASM 확대 판독에서 문단 원점·정렬·줄 간격·이어받기를 대조했다.
//! 각 문서의 모든 문단 내용을 순서대로 보존하고, 모든 첫 줄과 쪽을 넘는 줄의 원점을 검사한다.
//! 99%대 후보 쪽을 모두 포함하되 중요한 취소·정렬·쪽 나눔 경계도 함께 보호한다.
//! 시스템 글꼴을 로드하지 않는 기본 DocumentCore 경로이며 실제 glyph는 Visual Sweep으로 검증한다.

use rhwp::{
    document_core::DocumentCore,
    renderer::render_tree::{RenderNode, RenderNodeType},
};
use std::collections::BTreeMap;

const SHORT: &str = "가나다라마바사아";
const LONG: &str = "한글문서의문단모양에는첫줄들여쓰기가있는데이값을정렬방식과함께바꾸면서저장된줄정보가없는문서를한글이어떻게다시나누는지살펴보려고이문장을충분히길게적어둔다.";

struct Line {
    page: u32,
    text: String,
    x: f64,
    baseline: f64,
}
// (원본 문단 index, 문단 안 줄 index, 1부터 쪽, PDF 첫 글자 x, PDF 기준선 y)
type Anchor = (usize, usize, u32, f64, f64);
fn compact(text: &str) -> String {
    text.chars().filter(|c| !c.is_whitespace()).collect()
}

fn collect(node: &RenderNode, page: u32, out: &mut BTreeMap<usize, Vec<Line>>) {
    if matches!(node.node_type, RenderNodeType::TextLine(_)) {
        let runs: Vec<_> = node
            .children
            .iter()
            .filter_map(|n| {
                if let RenderNodeType::TextRun(run) = &n.node_type {
                    if !compact(&run.text).is_empty() {
                        return Some((n, run));
                    }
                }
                None
            })
            .collect();
        if let Some((first, run)) = runs.first() {
            let pi = run.para_index.expect("원본 문단 소속");
            assert!(
                runs.iter().all(|(_, r)| r.para_index == Some(pi)),
                "한 줄의 문단 소속"
            );
            let text = runs
                .iter()
                .map(|(_, r)| compact(&r.text))
                .collect::<String>();
            let (_, baseline) = run
                .style
                .script_draw_metrics(run.style.font_size, first.bbox.y + run.baseline);
            out.entry(pi).or_default().push(Line {
                page,
                text,
                x: first.bbox.x,
                baseline,
            });
        }
        return;
    }
    for child in &node.children {
        collect(child, page, out);
    }
}

fn check(path: &str, pages: u32, paragraph_count: usize, anchors: &[Anchor]) {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(path);
    let core =
        DocumentCore::from_bytes(&std::fs::read(&path).expect("원본 fixture")).expect("문서 열기");
    assert_eq!(core.page_count(), pages, "독립 Print 전체 쪽수");
    let mut lines = BTreeMap::new();
    for page in 1..=pages {
        let tree = core
            .build_page_render_tree(page - 1)
            .expect("쪽 render tree");
        collect(&tree.root, page, &mut lines);
    }
    assert_eq!(lines.len(), paragraph_count, "가시 문단의 추가·누락 없음");
    for pi in 1..=paragraph_count {
        let group = lines.get(&pi).expect("원본 순서의 문단");
        let actual = group.iter().map(|l| l.text.as_str()).collect::<String>();
        assert_eq!(
            actual,
            if pi % 2 == 1 { SHORT } else { LONG },
            "문단 {pi}의 내용·순서·중복 보존"
        );
        for pair in group.windows(2) {
            assert!(
                pair[0].page < pair[1].page
                    || (pair[0].page == pair[1].page && pair[0].baseline < pair[1].baseline),
                "문단 {pi}의 줄 순서와 기준선 전진"
            );
        }
        if pi > 1 {
            let previous = lines[&(pi - 1)].last().unwrap();
            assert!(
                previous.page < group[0].page
                    || (previous.page == group[0].page && previous.baseline < group[0].baseline),
                "문단 사이 내용 순서"
            );
        }
    }
    for &(pi, line_index, page, x, y) in anchors {
        let line = &lines[&pi][line_index];
        assert_eq!(line.page, page, "문단 {pi} 줄 {line_index}의 Print 쪽 소속");
        assert!(
            (line.x - x).abs() <= 2.0,
            "문단 {pi} 줄 {line_index} x: Print {x}, 실제 {}",
            line.x
        );
        assert!(
            (line.baseline - y).abs() <= 2.0,
            "문단 {pi} 줄 {line_index} 기준선: Print {y}, 실제 {}",
            line.baseline
        );
    }
}

